import argparse
import json
from pathlib import Path


def main():
    ap = argparse.ArgumentParser(prog="mappa", description="MAPPA: offline drone-to-map change & blocked-road workflow")
    sub = ap.add_subparsers(dest="cmd", required=True)

    d = sub.add_parser("demo", help="generate a SIMULATED scene with known ground truth and run the full pipeline")
    d.add_argument("--out", default="demo_run")
    d.add_argument("--base-res", type=float, default=10.0, help="simulated base-imagery resolution in m (Sentinel-2 = 10)")

    r = sub.add_parser("run", help="run on real data (ODM orthophoto + base imagery + OSM roads)")
    r.add_argument("--ortho", required=True, help="ODM odm_orthophoto.tif (projected CRS, RGB or RGBA)")
    r.add_argument("--base", required=True, help="last-known-state imagery GeoTIFF (any CRS), e.g. Sentinel-2 RGB / OpenAerialMap")
    r.add_argument("--roads", required=True, help="road centrelines (GeoJSON/GPKG/SHP), e.g. exported from OSM")
    r.add_argument("--dsm", help="ODM odm_dem/dsm.tif (optional)")
    r.add_argument("--dem", help="base DEM, e.g. Copernicus GLO-30 (optional, needs --dsm)")
    r.add_argument("--out", default="mappa_out")
    r.add_argument("--grid-res", type=float, default=1.0)
    r.add_argument("--base-accuracy", type=float, default=10.0,
                   help="absolute horizontal accuracy (95%%, m) of the base imagery; dominates the error budget")
    r.add_argument("--blocked-frac", type=float, default=0.40)
    r.add_argument("--uncertain-frac", type=float, default=0.15)
    r.add_argument("--blocked-height", type=float, default=0.5)
    r.add_argument("--provenance", default="")

    p = sub.add_parser("plan", help="flight-plan numbers + lawnmower KML for a rectangle")
    p.add_argument("--lat", type=float, required=True)
    p.add_argument("--lon", type=float, required=True)
    p.add_argument("--width", type=float, default=600)
    p.add_argument("--height", type=float, default=500)
    p.add_argument("--alt", type=float, default=90)
    p.add_argument("--out", default="mission.kml")

    c = sub.add_parser("card", help="write the one-page pilot capture card PDF")
    c.add_argument("--out", default="capture_card.pdf")

    a = ap.parse_args()
    if a.cmd == "demo":
        from . import demo_data, pipeline
        out = Path(a.out)
        paths = demo_data.generate(str(out / "input"), base_res_m=a.base_res)
        rep = pipeline.run(paths["ortho"], paths["base"], paths["roads"], str(out / "output"), dsm=paths["dsm"],
                           dem=paths["dem"], simulated=True, truth=paths["truth"],
                           provenance="Synthetic scene generated by mappa.demo_data with a known injected GPS error.")
        _summary(rep)
    elif a.cmd == "run":
        from . import pipeline
        th = dict(blocked_frac=a.blocked_frac, uncertain_frac=a.uncertain_frac, blocked_height_m=a.blocked_height)
        rep = pipeline.run(a.ortho, a.base, a.roads, a.out, dsm=a.dsm, dem=a.dem, grid_res=a.grid_res,
                           base_acc95=a.base_accuracy, thresholds=th, provenance=a.provenance)
        _summary(rep)
    elif a.cmd == "plan":
        from . import planner
        print(json.dumps(planner.write_mission_kml(a.lat, a.lon, a.width, a.height, a.out, alt_m=a.alt), indent=2))
    elif a.cmd == "card":
        from . import planner
        planner.capture_card(a.out, planner.plan(600, 500, 90))
        print("wrote", a.out)


def _summary(rep):
    g, r = rep["georeferencing"], rep["roads"]
    print(f"\nArea: {rep['area_km2']} km2 | accuracy: {g['statement']}")
    if "validation" in rep:
        print("Synthetic validation vs known truth:", rep["validation"])
    print("Road length by status (m):", r["length_m_by_status"])
    for b in r["blocked_stretches"]:
        print(f"  BLOCKED  {b['road']}: {b['length_m']} m")
    print("Timing (s):", rep["processing_time_s"])
    print(rep["processing_time_statement"])
